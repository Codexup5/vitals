import fs from 'node:fs';
import path from 'node:path';
import * as prettier from 'prettier';
import StyleDictionary from 'style-dictionary';

import { toCssColor } from './color.mjs';

const TOOLING_ROOT = path.resolve(import.meta.dirname, '../..');
const TOKENS_DIR = 'src/shared/styles/tokens';
export const CONFIG_FILE = `${TOKENS_DIR}/config.json`;
export const OUTPUT_FILE = 'src/shared/styles/tokens.scss';
const GENERATED_LINE = `// Generated by tooling/design/tokens.mjs from ${TOKENS_DIR}: edit the tokens, then run pnpm tokens.`;

const CONFIG_FIELDS = ['prefix', 'names', 'layers'];
const LAYER_FIELDS = ['file', 'selector', 'theme', 'pointer'];
const SUPPORTED_TYPES = ['color', 'dimension', 'number', 'fontWeight', 'fontFamily'];
const ROOT_FONT_SIZE = 16;

export class TokenConfigError extends Error {}

const fail = (message) => {
  throw new TokenConfigError(message);
};

const isPlainObject = (value) => typeof value === 'object' && value !== null && !Array.isArray(value);

const checkFields = (object, allowed, where) => {
  for (const field of Object.keys(object)) {
    if (!allowed.includes(field)) fail(`${where}: unknown field "${field}"`);
  }
};

const isToken = (node) => isPlainObject(node) && '$value' in node;

const childEntries = (group) => Object.entries(group).filter(([key]) => !key.startsWith('$'));

// Every token of a DTCG tree with its dotted path and the $type it takes from itself or a group above it
const listTokens = (tree, parentPath = [], parentType = undefined) =>
  childEntries(tree).flatMap(([key, node]) => {
    if (!isPlainObject(node)) return [];
    const nodePath = [...parentPath, key];
    const type = node.$type ?? parentType;
    if (isToken(node)) return [{ path: nodePath.join('.'), type, value: node.$value }];
    return listTokens(node, nodePath, type);
  });

const readJson = (file, where) => {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    if (error instanceof SyntaxError) fail(`${where}: ${error.message}`);
    throw error;
  }
};

const isAlias = (value) => typeof value === 'string' && /^\{[^{}]+\}$/.test(value);

const toHexChannel = (component) =>
  Math.round(component * 255)
    .toString(16)
    .padStart(2, '0');

// The build emits the hex and the checks measure the components, so the two must name one colour
const checkColorHex = ({ path: tokenPath, value }, where) => {
  if (!isPlainObject(value) || value.hex === undefined || value.colorSpace !== 'srgb') return;
  const expected = `#${value.components.map(toHexChannel).join('')}`;
  if (value.hex.toLowerCase() !== expected) {
    fail(`${where}: token ${tokenPath} has hex ${value.hex}, but its components give ${expected}`);
  }
};

const checkDimension = ({ path: tokenPath, value }, where) => {
  const isDimensionObject =
    isPlainObject(value) && typeof value.value === 'number' && ['px', 'rem'].includes(value.unit);
  if (!isDimensionObject) {
    fail(`${where}: token ${tokenPath} is a dimension, so its $value is { "value": number, "unit": "px" | "rem" }`);
  }
};

const checkTokenValue = (token, where) => {
  if (!SUPPORTED_TYPES.includes(token.type)) {
    fail(`${where}: token ${token.path} has the unsupported $type "${token.type}"`);
  }
  if (isAlias(token.value)) return;
  if (token.type === 'color') checkColorHex(token, where);
  if (token.type === 'dimension') checkDimension(token, where);
};

const checkLayer = (layer, index, root) => {
  const where = `${CONFIG_FILE} layers[${index}]`;
  if (!isPlainObject(layer)) fail(`${where}: a layer is an object`);
  checkFields(layer, LAYER_FIELDS, where);
  if (typeof layer.file !== 'string') fail(`${where}: field "file" is missing`);
  if (index > 0 && !Array.isArray(layer.selector)) fail(`${where}: field "selector" is missing`);
  if (layer.pointer !== undefined && layer.pointer !== 'coarse') fail(`${where}: field "pointer" is only "coarse"`);
  if (index > 0 && layer.theme === undefined && layer.pointer === undefined) {
    fail(`${where}: a layer has "theme" or "pointer", the contexts the design checks judge it in`);
  }
  const file = path.join(root, TOKENS_DIR, layer.file);
  if (!fs.existsSync(file)) fail(`${where}: file ${TOKENS_DIR}/${layer.file} does not exist`);
  return { ...layer, path: file };
};

export const readTokenConfig = (root) => {
  const file = path.join(root, CONFIG_FILE);
  if (!fs.existsSync(file)) return null;
  const config = readJson(file, CONFIG_FILE);
  if (!isPlainObject(config)) fail(`${CONFIG_FILE}: the config is an object`);
  checkFields(config, CONFIG_FIELDS, CONFIG_FILE);
  const { prefix = '', names = {}, layers } = config;
  if (typeof prefix !== 'string') fail(`${CONFIG_FILE}: field "prefix" is a string`);
  if (!isPlainObject(names)) fail(`${CONFIG_FILE}: field "names" is an object`);
  if (!Array.isArray(layers) || layers.length === 0) fail(`${CONFIG_FILE}: field "layers" lists at least one layer`);
  const checkedLayers = layers.map((layer, index) => checkLayer(layer, index, root));

  const paths = new Set();
  const aliases = [];
  for (const layer of checkedLayers) {
    const where = `${TOKENS_DIR}/${layer.file}`;
    for (const token of listTokens(readJson(layer.path, where))) {
      checkTokenValue(token, where);
      if (isAlias(token.value)) aliases.push({ ...token, where });
      paths.add(token.path);
    }
  }
  for (const { path: tokenPath, value, where } of aliases) {
    const target = value.slice(1, -1);
    if (!paths.has(target)) fail(`${where}: token ${tokenPath} refers to ${value}, which is not a token`);
  }
  for (const tokenPath of Object.keys(names)) {
    if (!paths.has(tokenPath)) fail(`${CONFIG_FILE}: field "names" maps ${tokenPath}, which is not a token`);
  }
  return { prefix, names, layers: checkedLayers };
};

// The $extensions.kit of a group reaches every token below it; the fields of the token win
const inheritRoles = (tree, inherited = {}) => {
  for (const [, node] of childEntries(tree)) {
    if (!isPlainObject(node)) continue;
    const kit = { ...inherited, ...node.$extensions?.kit };
    if (isToken(node)) {
      if (Object.keys(kit).length > 0) node.$extensions = { ...node.$extensions, kit };
    } else {
      inheritRoles(node, kit);
    }
  }
  return tree;
};

const toShortHex = (hex) => {
  const lower = hex.toLowerCase();
  const pairs = lower.match(/^#(.)\1(.)\2(.)\3$/);
  return pairs ? `#${pairs[1]}${pairs[2]}${pairs[3]}` : lower;
};

const toCssColorValue = (value) => {
  if (typeof value === 'string') return toShortHex(value);
  const { hex, alpha = 1 } = value;
  return hex && alpha === 1 ? toShortHex(hex) : toCssColor(value);
};

const toCssDimension = (value, role) => {
  if (typeof value === 'string') return value;
  if (role === 'font-size' && value.unit === 'px') return `${value.value / ROOT_FONT_SIZE}rem`;
  return `${value.value}${value.unit}`;
};

const toCssFontFamily = (value) =>
  Array.isArray(value) ? value.map((name) => (name.includes(' ') ? `'${name}'` : name)).join(', ') : value;

const tokenValue = (token) => token.$value ?? token.value;

export const createHooks = ({ prefix, names }) => ({
  preprocessors: { 'kit/roles': (tokens) => inheritRoles(tokens) },
  transforms: {
    'kit/name': {
      type: 'name',
      transform: (token) => {
        const name = names[token.path.join('.')] ?? token.path.join('-');
        return prefix ? `${prefix}-${name}` : name;
      },
    },
    'kit/color': {
      type: 'value',
      filter: (token) => token.$type === 'color',
      transform: (token) => toCssColorValue(tokenValue(token)),
    },
    'kit/dimension': {
      type: 'value',
      filter: (token) => token.$type === 'dimension',
      transform: (token) => toCssDimension(tokenValue(token), token.$extensions?.kit?.role),
    },
    'kit/font-family': {
      type: 'value',
      filter: (token) => token.$type === 'fontFamily',
      transform: (token) => toCssFontFamily(tokenValue(token)),
    },
  },
});

const TRANSFORMS = ['kit/name', 'kit/color', 'kit/dimension', 'kit/font-family'];

// Style Dictionary reads its sources through a glob, which takes forward slashes only
const toGlobPath = (file) => file.split(path.sep).join('/');

// One Style Dictionary instance of the kit setup, shared by the build and the contexts of the checks
export const createDictionary = ({ hooks, include, source, platforms }) =>
  new StyleDictionary({
    include: include.map(toGlobPath),
    source: source.map(toGlobPath),
    preprocessors: ['kit/roles'],
    hooks,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms,
  });

const buildLayer = async (layer, index, base, hooks) => {
  const dictionary = createDictionary({
    hooks,
    include: index === 0 ? [] : [base.path],
    source: [layer.path],
    platforms: {
      css: {
        transforms: TRANSFORMS,
        files: [
          {
            destination: 'tokens.scss',
            format: 'css/variables',
            ...(index === 0 ? {} : { filter: (token) => token.isSource }),
            options: { selector: layer.selector, outputReferences: true, showFileHeader: false },
          },
        ],
      },
    },
  });
  const [file] = await dictionary.formatPlatform('css');
  return file.output.trimEnd();
};

export const buildTokens = async (config) => {
  const hooks = createHooks(config);
  const [base] = config.layers;
  const blocks = [];
  for (const [index, layer] of config.layers.entries()) blocks.push(await buildLayer(layer, index, base, hooks));
  const text = `${GENERATED_LINE}\n${blocks.join('\n\n')}\n`;
  const { plugins = [], ...options } = (await prettier.resolveConfig(path.join(TOOLING_ROOT, OUTPUT_FILE))) ?? {};
  // prettier imports a plugin named in the config from the cwd, which is not the project under --root
  const resolvedPlugins = plugins.map((plugin) => (typeof plugin === 'string' ? import.meta.resolve(plugin) : plugin));
  return prettier.format(text, { ...options, plugins: resolvedPlugins, parser: 'scss' });
};
