#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

import { SEGMENTS } from '../tooling/placement.mjs';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'src');
const OUTPUT = path.join(ROOT, 'docs', 'context', 'public-api.md');
const SLICE_LAYERS = ['features', 'entities', 'pages'];
const SOURCE_FILE = /\.(ts|tsx)$/;
const IGNORED_FILE = /\.(test|d)\.tsx?$/;

const toPosix = (filePath) => filePath.split(path.sep).join('/');
const listDirectories = (directory) =>
  fs.existsSync(directory)
    ? fs
        .readdirSync(directory, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
        .sort()
    : [];

const listFiles = (directory) =>
  fs.existsSync(directory)
    ? fs
        .readdirSync(directory, { withFileTypes: true, recursive: true })
        .filter((entry) => entry.isFile() && SOURCE_FILE.test(entry.name) && !IGNORED_FILE.test(entry.name))
        .map((entry) => path.join(entry.parentPath, entry.name))
        .sort()
    : [];

const parseReexports = (source) =>
  [...source.matchAll(/export\s+(type\s+)?\{([^}]+)\}\s+from\s+'([^']+)'/g)].flatMap(([, typeOnly, names, from]) =>
    names
      .split(',')
      .map((name) => name.trim())
      .filter(Boolean)
      .map((name) => {
        const isType = Boolean(typeOnly) || name.startsWith('type ');
        const exported = name
          .replace(/^type\s+/, '')
          .split(/\s+as\s+/)
          .at(-1);
        return { name: exported, isType, from };
      }),
  );

const parseDeclarations = (source) =>
  [...source.matchAll(/export\s+(?:declare\s+)?(const|function|class|type|interface)\s+([A-Za-z0-9_]+)/g)].map(
    ([, kind, name]) => ({ name, isType: kind === 'type' || kind === 'interface' }),
  );

const formatNames = (exports) => {
  const values = exports.filter((entry) => !entry.isType).map((entry) => `\`${entry.name}\``);
  const types = exports.filter((entry) => entry.isType).map((entry) => `\`${entry.name}\``);
  return [values.join(', '), types.length > 0 ? `types: ${types.join(', ')}` : ''].filter(Boolean).join(' · ');
};

const hasIndex = (layer, slice) => fs.existsSync(path.join(SRC, layer, slice, 'index.ts'));

const listSlices = (layer) =>
  listDirectories(path.join(SRC, layer)).flatMap((folder) => {
    const groupSlices =
      layer === 'pages' && !hasIndex(layer, folder)
        ? listDirectories(path.join(SRC, layer, folder))
            .filter((child) => !SEGMENTS.includes(child))
            .map((child) => `${folder}/${child}`)
            .filter((slice) => hasIndex(layer, slice))
        : [];
    return groupSlices.length > 0 ? groupSlices : [folder];
  });

const renderSliceLayer = (layer) => {
  const slices = listSlices(layer);
  if (slices.length === 0) return [];
  const lines = [`## ${layer}`, ''];
  for (const slice of slices) {
    const indexPath = path.join(SRC, layer, slice, 'index.ts');
    const exports = fs.existsSync(indexPath) ? parseReexports(fs.readFileSync(indexPath, 'utf8')) : [];
    lines.push(`- **\`@/${layer}/${slice}\`** — ${exports.length > 0 ? formatNames(exports) : 'no public API'}`);
  }
  return [...lines, ''];
};

const renderShared = () => {
  const files = listFiles(path.join(SRC, 'shared'));
  if (files.length === 0) return [];
  const lines = ['## shared', '', 'Import by the direct file path.', ''];
  for (const file of files) {
    const exports = parseDeclarations(fs.readFileSync(file, 'utf8'));
    if (exports.length === 0) continue;
    const importPath = `@/${toPosix(path.relative(SRC, file)).replace(SOURCE_FILE, '')}`;
    lines.push(`- \`${importPath}\` — ${formatNames(exports)}`);
  }
  return [...lines, ''];
};

const content = [
  '# Public API',
  '',
  'Generated by `pnpm context` from slice `index.ts` files and `shared` exports. Not edited by hand.',
  'Before creating a component, hook or helper, look for it here.',
  '',
  ...renderShared(),
  ...SLICE_LAYERS.flatMap(renderSliceLayer),
]
  .join('\n')
  .replace(/\n+$/, '\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (current !== content) {
    console.error('docs/context/public-api.md is stale: run `pnpm context` and commit the result.');
    process.exit(1);
  }
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, content);
console.log(`public API → ${toPosix(path.relative(ROOT, OUTPUT))}`);
