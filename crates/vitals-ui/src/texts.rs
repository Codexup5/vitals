#[derive(Debug)]
pub struct Kinds {
    pub crash: &'static str,
    pub bsod: &'static str,
    pub whea: &'static str,
    pub gpu_reset: &'static str,
    pub app_crash: &'static str,
    pub nv_container: &'static str,
    pub iommu: &'static str,
    pub error: &'static str,
}

impl Kinds {
    pub const fn of(&self, kind: FeedKind) -> &'static str {
        match kind {
            FeedKind::Crash => self.crash,
            FeedKind::Bsod => self.bsod,
            FeedKind::Whea => self.whea,
            FeedKind::GpuReset => self.gpu_reset,
            FeedKind::AppCrash => self.app_crash,
            FeedKind::NvContainer => self.nv_container,
            FeedKind::Iommu => self.iommu,
            FeedKind::Error => self.error,
        }
    }
}

