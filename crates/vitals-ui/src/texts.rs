#[derive(Debug)]
pub struct Disk {
    pub categories: [&'static str; 8],
    pub candidates: [(&'static str, &'static str); 12],
}

impl Disk {
    pub fn category(&self, category: Category) -> &'static str {
        let index = Category::ALL
            .iter()
            .position(|known| *known == category)
            .unwrap_or(Category::ALL.len() - 1);
        self.categories[index]
    }

    /// The title and the hint of a candidate
    pub const fn candidate(&self, kind: CandidateKind) -> (&'static str, &'static str) {
        self.candidates[kind as usize]
    }
}

